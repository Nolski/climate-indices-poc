#!/usr/bin/env bash
# Measures the weight of the front end and writes BUDGET.md.
#
#   web/measure.sh                       sizes on disk, raw and gzip -9
#   web/measure.sh --url http://127.0.0.1:8000    also fetch every first-load file from a running
#                                        server to see what really crosses the wire, and time the
#                                        first load through a simulated slow link (needs node)
#   web/measure.sh --check               print the result without rewriting BUDGET.md
#
# Exit status is 1 if the first load is over the budget.
set -euo pipefail
cd "$(dirname "$0")"

BUDGET_KB=150
URL=""
OUT=BUDGET.md
if [ "${1:-}" = "--url" ]; then URL="${2%/}"; fi
if [ "${1:-}" = "--check" ]; then OUT=$(mktemp); trap 'rm -f "$OUT"' EXIT; fi

raw() { wc -c < "$1" | tr -d ' '; }
gz() { gzip -9 -c "$1" | wc -c | tr -d ' '; }
kb() { awk -v b="$1" 'BEGIN { printf "%.1f", b / 1024 }'; }

# First load = the page, its stylesheet, every module it preloads, and the English strings.
mapfile -t MODULES < <(grep -o 'rel="modulepreload" href="[^"]*"' index.html | sed 's/.*href="//; s/"$//')
FIRST=(index.html css/app.css "${MODULES[@]}" i18n/en.json)
ON_DEMAND=(i18n/fr.json)

{
  echo "# Page weight budget"
  echo
  echo "Generated by \`web/measure.sh\` on $(date -u +%Y-%m-%d). Do not edit by hand; run the script again."
  echo
  echo "Budget: first load under **${BUDGET_KB} KB gzipped** (HTML + CSS + JavaScript + interface text),"
  echo "no web fonts, no image over 5 KB."
  echo
  echo "## First load"
  echo
  echo "| File | Raw (bytes) | Gzipped (bytes) | Gzipped (KB) |"
  echo "|---|---:|---:|---:|"
} > "$OUT"

total_raw=0
total_gz=0
for f in "${FIRST[@]}"; do
  r=$(raw "$f"); g=$(gz "$f")
  total_raw=$((total_raw + r)); total_gz=$((total_gz + g))
  echo "| \`$f\` | $r | $g | $(kb "$g") |" >> "$OUT"
done
echo "| **Total (${#FIRST[@]} requests)** | **$total_raw** | **$total_gz** | **$(kb "$total_gz")** |" >> "$OUT"

status="within"
if [ "$total_gz" -gt $((BUDGET_KB * 1024)) ]; then status="OVER"; fi
pct=$(awk -v g="$total_gz" -v b="$BUDGET_KB" 'BEGIN { printf "%.0f", g / (b * 1024) * 100 }')

fonts=$(find . -path ./fixtures -prune -o -type f \( -name '*.woff' -o -name '*.woff2' -o -name '*.ttf' -o -name '*.otf' \) -print | wc -l | tr -d ' ')
images=$(find . -path ./fixtures -prune -o -type f \( -name '*.png' -o -name '*.jpg' -o -name '*.jpeg' -o -name '*.gif' -o -name '*.webp' -o -name '*.ico' -o -name '*.svg' \) -print | wc -l | tr -d ' ')
vendor=$({ find vendor -type f 2>/dev/null || true; } | wc -l | tr -d ' ')

# Time to fetch the first load: 4 round trips (connect + page, connect + assets in parallel)
# plus the bytes at the link speed. Chrome DevTools presets: Slow 3G = 400 kbit/s, 400 ms;
# Fast 3G = 1.6 Mbit/s, 150 ms. This is arithmetic, not a browser measurement.
est() { awk -v g="$total_gz" -v kbps="$1" -v rtt="$2" 'BEGIN { printf "%.1f", 4 * rtt / 1000 + g * 8 / (kbps * 1000) }'; }

{
  echo
  echo "Result: **$(kb "$total_gz") KB gzipped, $pct% of the ${BUDGET_KB} KB budget ($status budget).**"
  echo "Uncompressed, the same files are $(kb "$total_raw") KB."
  echo
  echo "- Web fonts: $fonts files (system font stack only)."
  echo "- Image files: $images (all icons are inline SVG inside \`index.html\`)."
  echo "- Third-party code: $vendor files (no chart library; the chart is \`js/chart.js\`)."
  echo
  echo "## Loaded only when needed"
  echo
  echo "| File | When | Raw (bytes) | Gzipped (bytes) |"
  echo "|---|---|---:|---:|"
  for f in "${ON_DEMAND[@]}"; do echo "| \`$f\` | when the language is switched | $(raw "$f") | $(gz "$f") |"; done
  echo
  echo "## Data from the API (not part of the page itself)"
  echo
  echo "Sizes of the example responses in \`fixtures/\` for the 80-year sample station. They show what"
  echo "each step costs on the wire if the server compresses its responses."
  echo
  echo "| Response | When | Raw (bytes) | Gzipped (bytes) |"
  echo "|---|---|---:|---:|"
  for row in "version.json|on first load" "indices.json|on first load, then cached in the browser" "dataset.json|step 1, after loading data" "daily_tasmax.json|step 2, only if the daily chart is opened" "compute_annual.json|step 3, yearly values for all indices" "compute_monthly.json|step 3, monthly values for all indices"; do
    f="fixtures/${row%%|*}"
    if [ -f "$f" ]; then echo "| \`$f\` | ${row##*|} | $(raw "$f") | $(gz "$f") |"; fi
  done
  echo
  echo "## Estimated time to fetch the first load"
  echo
  echo "Arithmetic from the total above (4 network round trips plus the bytes at the link speed);"
  echo "it is **not** a browser measurement and excludes script start-up, which is small for"
  echo "$(kb "$total_raw") KB of plain modules."
  echo
  echo "| Connection | Speed, round-trip time | Estimate |"
  echo "|---|---|---:|"
  echo "| Slow 3G (browser throttling preset) | 400 kbit/s, 400 ms | $(est 400 400) s |"
  echo "| Fast 3G | 1.6 Mbit/s, 150 ms | $(est 1600 150) s |"
  echo "| 10 Mbit/s office link | 10 Mbit/s, 100 ms | $(est 10000 100) s |"
  echo
  echo "These figures assume the server compresses its responses (gzip or better) and lets the"
  echo "browser reuse cached files. Without compression the first load is $(kb "$total_raw") KB,"
  echo "which is over the budget: compression on the server is required, not optional. Run"
  echo "\`web/measure.sh --url http://HOST:PORT\` against the running server to confirm it."
} >> "$OUT"

if [ -n "$URL" ]; then
  {
    echo
    echo "## Measured over HTTP from \`$URL\`"
    echo
    echo "What the running server really sends for each first-load file (\`curl --compressed\`)."
    echo
    echo "| File | Bytes on the wire | Content-Encoding | Cache-Control |"
    echo "|---|---:|---|---|"
  } >> "$OUT"
  wire=0
  for f in "${FIRST[@]}"; do
    p="$f"; [ "$f" = "index.html" ] && p=""
    hdr=$(mktemp)
    read -r size code < <(curl -s --compressed -D "$hdr" -o /dev/null -w '%{size_download} %{http_code}\n' "$URL/$p" || echo "0 000")
    enc=$(grep -i '^content-encoding:' "$hdr" | tr -d '\r' | sed 's/^[^:]*: *//' | head -1)
    cc=$(grep -i '^cache-control:' "$hdr" | tr -d '\r' | sed 's/^[^:]*: *//' | head -1)
    rm -f "$hdr"
    wire=$((wire + size))
    echo "| \`$f\` (HTTP $code) | $size | ${enc:-none} | ${cc:-none} |" >> "$OUT"
  done
  echo "| **Total** | **$wire** | | |" >> "$OUT"
  {
    echo
    echo "Total on the wire: **$(kb "$wire") KB**."
    echo
    echo "### Timed through a simulated slow link"
    echo
    echo "\`tests/slow_link.mjs\` puts a throttling proxy in front of the server (one shared downlink,"
    echo "a round trip of delay per request and per new connection, six parallel connections) and"
    echo "fetches the files in the order a browser does. Script start-up and drawing are not"
    echo "included, and no real browser was involved."
    echo
    echo "| Link | Page text arrives | Page is styled | All scripts and text loaded | First data from the API |"
    echo "|---|---:|---:|---:|---:|"
  } >> "$OUT"
  for profile in "Very slow (250 kbit/s, 600 ms)|250|600" "Slow 3G (400 kbit/s, 400 ms)|400|400" "Fast 3G (1.6 Mbit/s, 150 ms)|1600|150"; do
    IFS='|' read -r label kbps rtt <<< "$profile"
    json=$(node tests/slow_link.mjs "$URL" "$kbps" "$rtt" | tail -1)
    row=$(node -e 'const r=JSON.parse(process.argv[1]);const s=(ms)=>(ms/1000).toFixed(1)+" s";console.log([s(r.pageMs),s(r.styledMs),s(r.assetsMs),s(r.dataMs)].join(" | "))' "$json")
    echo "| $label | $row |" >> "$OUT"
    echo "Simulated $label: $row (page | styled | all scripts | first API data)"
  done
fi

echo "First load: $total_raw bytes raw, $total_gz bytes gzipped ($(kb "$total_gz") KB) in ${#FIRST[@]} requests: $pct% of the ${BUDGET_KB} KB budget ($status budget)."
echo "Estimated fetch time on Slow 3G (400 kbit/s, 400 ms): $(est 400 400) s."
if [ "$OUT" = "BUDGET.md" ]; then echo "Written to web/BUDGET.md."; fi
[ "$status" = "within" ]
